package ch06.sec08.exam01;

public class Calculator {

    static void powerOn() {
        System.out.println("전원을 켭니다.");
    }

    static int plus(int a, int b) {
        return a + b;
    }

    static double divide(int x, int y) {
        return (double) x / y;
    }

    static void powerOff() {
        System.out.println("전원을 끕니다.");
    }
}
